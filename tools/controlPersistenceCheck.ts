import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { Database } from "../src/database/service/database.ts";
import { openStore, putObject, verifyObjectChain } from "../src/database/store/database.ts";
import { Schema } from "../src/database/sql/schema.ts";
import { SessionRegistry } from "../src/session/registry.ts";
import { registerCatalogWriteGuard } from "../src/database/store/catalogGuard.ts";

const folder = mkdtempSync(join(tmpdir(), "amp-control-"));
try {
    const path = join(folder, "state.sqlite");
    let database = new Database(path);
    const service = database.controlService;
    service.createWorkspace("a", "A"); service.createWorkspace("b", "B");
    const registry = new SessionRegistry({ store: database.workspaceSessions });
    const open = (workspaceId: string) => registry.open({ agentId: workspaceId, workspaceId, roots: [{ id: `root-${workspaceId}`, path: process.cwd(), writable: false, exclude: [] }] });
    const aSession = open("a"); const bSession = open("b");
    assert.equal(registry.fork(aSession.descriptor.id).descriptor.workspaceId, "a");
    const a = service.bind({ workspaceId: "a", sessionId: aSession.descriptor.id });
    const b = service.bind({ workspaceId: "b", sessionId: bSession.descriptor.id });
    const global = service.bind({ workspaceId: "a", allowGlobal: true });
    const limited = service.bind({ workspaceId: "a", allowGlobal: true, authorizedWorkspaceIds: ["a"] });
    const call = (port: typeof a, scope: "global" | "workspace" | "session", domain: "adjust" | "interaction" | "scenario", args: Record<string, unknown>) => port.call(scope, domain, args);
    const rejects = (fn: () => unknown, code: string) => assert.throws(fn, (error: unknown) => error instanceof Error && error.message === code);
    rejects(() => call(a, "global", "interaction", { action: "get" }), "permission_denied");
    rejects(() => call(limited, "global", "interaction", { action: "set", mode: "think" }), "permission_denied");
    rejects(() => call(a, "workspace", "interaction", { action: "get", workspaceId: "b" }), "invalid_arguments");
    call(global, "global", "interaction", { action: "set", mode: "think", expectedVersion: 0 });
    assert.equal(call(a, "session", "interaction", { action: "get" }).source, "global");
    call(a, "workspace", "interaction", { action: "set", mode: "converge", expectedVersion: 0 });
    assert.equal(call(a, "session", "interaction", { action: "get" }).source, "workspace");
    rejects(() => call(a, "workspace", "interaction", { action: "set", mode: "affect", expectedVersion: 0 }), "version_conflict");
    for (const mix of [{ think: -1 }, { think: "1" }, { think: 0 }, { bogus: 1 }]) rejects(() => call(a, "workspace", "interaction", { action: "set", mix }), "invalid_arguments");
    const before = database.db.prepare("SELECT total_changes() AS n").get() as { n: number };
    call(a, "session", "scenario", { action: "set", scenario: "engineering", dryRun: true });
    call(a, "workspace", "adjust", { action: "register", registry: "skills", id: "dry", value: { label: "Dry" }, dryRun: true });
    call(a, "workspace", "adjust", { action: "default_set", registry: "skills", key: "main", value: "dry", dryRun: true });
    assert.equal((database.db.prepare("SELECT total_changes() AS n").get() as { n: number }).n, before.n);
    rejects(() => call(a, "workspace", "adjust", { action: "register", registry: "skills", id: "bad", value: { nested: { policy: {} } } }), "invalid_arguments");
    const weird: unknown[] & { extra?: number } = new Array(1); weird.extra = 1;
    rejects(() => call(a, "workspace", "adjust", { action: "register", registry: "skills", id: "bad", value: { nested: weird } }), "invalid_arguments");
    call(global, "global", "adjust", { action: "register", registry: "skills", id: "shared", value: { label: "Shared" } });
    assert.equal((call(a, "workspace", "adjust", { action: "list", registry: "skills" }).entries as unknown[]).length, 1);
    call(a, "workspace", "adjust", { action: "remove", registry: "skills", id: "shared", expectedVersion: 0 });
    assert.equal(service.listRegistry("a", "skills").length, 0);
    assert.equal(service.listRegistry("a", "skills", true)[0].status, "removed");
    assert.equal(service.listRegistry("b", "skills").length, 1);
    call(global, "global", "adjust", { action: "default_set", registry: "skills", key: "main", value: "shared" });
    assert.equal(call(a, "workspace", "adjust", { action: "default_get", registry: "skills", key: "main" }).value, "shared");
    call(a, "workspace", "adjust", { action: "default_set", registry: "skills", key: "main", value: "local" });
    assert.equal(call(a, "workspace", "adjust", { action: "default_reset", registry: "skills", key: "main" }).value, "shared");
    call(limited, "global", "scenario", { action: "set", workspaceId: "a", scenario: "research", applyTo: "existing" });
    assert.equal(call(a, "session", "scenario", { action: "get" }).source, "session");
    assert.equal(call(b, "session", "scenario", { action: "get" }).mix, null);
    database.db.exec("BEGIN");
    rejects(() => call(a, "session", "scenario", { action: "get" }), "control_unavailable");
    database.db.exec("ROLLBACK");
    rejects(() => service.bind({ workspaceId: "a", authenticate: (() => Promise.resolve()) as unknown as () => void }).call("workspace", "scenario", { action: "get" }), "permission_denied");
    const authenticated = service.bind({ workspaceId: "a", sessionId: aSession.descriptor.id, authenticate: () => { registry.authenticate(aSession.credential.sessionId, aSession.credential.token); } });
    assert.equal(authenticated.call("session", "scenario", { action: "get" }).source, "session");
    const oldDefault = service.defaultWorkspace();
    assert.equal(service.setDefaultWorkspace("a", oldDefault.version).workspaceId, "a");
    assert.equal(registry.open({ agentId: "default-follow", roots: [{ id: "default-follow-root", path: process.cwd(), writable: false, exclude: [] }] }).descriptor.workspaceId, "a");
    registry.revoke(aSession.descriptor.id);
    rejects(() => call(a, "session", "scenario", { action: "get" }), "permission_denied");
    database.close();
    database = new Database(path);
    assert.equal(database.controlService.defaultWorkspace().workspaceId, "a");
    assert.equal(database.controlService.listRegistry("a", "skills", true)[0].status, "removed");
    assert.equal(database.workspaceSessions.load(bSession.descriptor.id)?.workspaceId, "b");
    database.close();

    // Construct an actual old schema without workspace_id, preserving scheduler/evidence.
    const legacyPath = join(folder, "legacy.sqlite");
    const legacy = new DatabaseSync(legacyPath); registerCatalogWriteGuard(legacy);
    const oldSchema = Schema.slice(0, Schema.indexOf("/* A workspace is")) + `
      CREATE TABLE workspace_sessions(session_id TEXT PRIMARY KEY,agent_id TEXT NOT NULL,label TEXT NOT NULL,status TEXT NOT NULL,token_hash TEXT NOT NULL,permissions_json TEXT NOT NULL,created_at TEXT NOT NULL,expires_at TEXT NOT NULL,idle_expires_at TEXT NOT NULL,revision INTEGER NOT NULL DEFAULT 0,parent_id TEXT,metadata_json TEXT NOT NULL DEFAULT '{}');
      CREATE TABLE meta(key TEXT PRIMARY KEY,value TEXT NOT NULL);
      INSERT INTO meta VALUES('schema_version','4');
      INSERT INTO workspace_sessions VALUES('old','agent','old','active','hash','{}','2026','2099','2099',0,NULL,'{}');
      INSERT INTO processes(id,name,state,budget,used,created_at) VALUES('preserved','preserved','created','{}','{}','2026');`;
    legacy.exec(oldSchema); putObject(legacy, "evidence", "preserved", { value: 1 }, new Date().toISOString()); legacy.close();
    let migrated = openStore(legacyPath);
    assert.equal((migrated.prepare("SELECT workspace_id FROM workspace_sessions").get() as { workspace_id: string }).workspace_id, "default");
    assert.equal((migrated.prepare("SELECT count(*) n FROM processes").get() as { n: number }).n, 1);
    assert.equal(verifyObjectChain(migrated).ok, true);
    assert.throws(() => migrated.prepare("UPDATE workspace_sessions SET workspace_id='missing'").run());
    migrated.close(); migrated = openStore(legacyPath);
    assert.equal((migrated.prepare("SELECT count(*) n FROM processes").get() as { n: number }).n, 1);
    assert.equal(verifyObjectChain(migrated).ok, true);
    migrated.prepare("UPDATE meta SET value='999' WHERE key='schema_version'").run(); migrated.close();
    assert.throws(() => openStore(legacyPath), /unsupported schema version/);
    const future = new DatabaseSync(legacyPath);
    assert.equal((future.prepare("SELECT count(*) n FROM processes").get() as { n: number }).n, 1); future.close();
    console.log("controlPersistenceCheck: migration, identity, inheritance, isolation, CAS, dryRun, batch and reopen passed");
} finally {
    try { rmSync(folder, { recursive: true, force: true }); } catch { console.error(`Retained open debug database: ${folder}`); }
}
