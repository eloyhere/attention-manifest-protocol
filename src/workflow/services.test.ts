import assert from "node:assert/strict";
import { test } from "node:test";
import { SessionService } from "../session/index.ts";
import { TurnService } from "../turn/index.ts";
import { IntentService } from "../intent/index.ts";
import { MissionService } from "../mission/index.ts";
import { GoalService } from "../goal/index.ts";
import { PlanService } from "../plan/index.ts";
import { TaskService } from "../task/index.ts";
import { ActionService } from "../action/index.ts";
import { WorkflowStore } from "./store.ts";
import type { Acceptance, TransitionOptions } from "./types.ts";

const verified: Acceptance = { valid: true, contractVersion: "v1", verificationId: "verification", evidenceIds: ["evidence"] };
const options = (version: number): TransitionOptions => ({ actor: "host", expectedVersion: version, cancellationEpoch: 0 });
const fixture = () => {
    const store = new WorkflowStore(() => "2026-01-01T00:00:00Z");
    const session = new SessionService(store);
    const turn = new TurnService(store);
    const intent = new IntentService(store);
    const mission = new MissionService(store);
    const goal = new GoalService(store);
    const plan = new PlanService(store);
    const task = new TaskService(store);
    const action = new ActionService(store);
    session.create({ id: "s", sessionId: "s", participants: ["user"] }, "host");
    session.activate("s", options(0));
    turn.create({ id: "t", sessionId: "s", classification: "new_intent" }, "host");
    turn.interpret("t", options(0));
    intent.create({ id: "i", sessionId: "s", originTurnId: "t", text: "verified effect" }, "host");
    intent.confirm("i", options(0));
    intent.accept("i", options(1));
    mission.create({ id: "m", sessionId: "s", intentId: "i" }, "host");
    mission.activate("m", options(0));
    goal.create({ id: "g", sessionId: "s", missionId: "m", acceptanceCriteria: ["effect verified"], contractVersion: "v1" }, "host");
    goal.activate("g", options(0));
    plan.create({ id: "p", sessionId: "s", goalId: "g", bounds: { maxAttempts: 2, deadline: "2027-01-01T00:00:00Z", progressMetric: "accepted effects", deadLetterOwner: "operator" } }, "host");
    task.create({ id: "k", sessionId: "s", planId: "p", dependsOn: [], required: true, contractVersion: "v1", requiredEffects: ["effect"] }, "host");
    plan.ready("p", options(0));
    plan.start("p", options(1));
    task.ready("k", options(0));
    task.start("k", options(1));
    action.create({ id: "a", sessionId: "s", originTurnId: "t", taskId: "k", operationId: "operation", required: true, effect: "effect", sideEffect: true, recovery: "query" }, "host");
    action.ready("a", options(0));
    return { store, session, turn, intent, mission, goal, plan, task, action };
};

test("domain services share the sole store and preserve version, acceptance and execution guards", () => {
    const { store, turn, goal, plan, task, action } = fixture();
    assert.deepEqual(action.get("a"), store.get("action", "a"));
    assert.equal(action.find("missing").isEmpty(), true);
    assert.equal(action.find("a").map(value => value.operationId).orElse("missing"), "operation");
    assert.equal(action.findAttempt("missing").isEmpty(), true);
    assert.equal(plan.tasks("p")[0].id, "k");
    assert.equal(plan.bounds("p").maxAttempts, 2);
    assert.equal(task.actions("k")[0].operationId, "operation");
    assert.throws(() => action.ready("a", options(0)), { code: "version_conflict" });
    action.assertExecutionAllowed("a", 0);
    action.startAttempt("a", { ...options(1), cancellationEpoch: 0, executionId: "execution", attemptId: "attempt" });
    turn.respond("t", options(1));
    turn.complete("t", options(2));
    assert.equal(action.getAttempt("attempt").state, "running");
    assert.equal(action.findAttempt("attempt").flatMap(attempt => action.find(attempt.actionId)).map(value => value.id).orElse("missing"), "a");
    action.settleAttempt("attempt", { actor: "executor", expectedVersion: 0, expectedActionVersion: 2, outcome: "succeeded" });
    task.succeed("k", verified, options(2));
    plan.complete("p", options(2));
    goal.achieve("g", verified, options(1));
    const achievedAt = goal.get("g").achievedAt;
    goal.invalidate("g", { ...options(2), reason: "evidence revoked" });
    assert.equal(store.get("goal", "g").validity, "invalidated");
    goal.revalidate("g", verified, options(3));
    assert.equal(goal.get("g").achievedAt, achievedAt);
    assert.equal(goal.get("g").validity, "valid");
    assert.equal(action.attempts("a").length, 1);
});

test("domain services retain unknown outcome reconciliation and cancellation fences", () => {
    const { action, mission, store } = fixture();
    action.startAttempt("a", { ...options(1), cancellationEpoch: 0, executionId: "execution", attemptId: "attempt" });
    action.settleAttempt("attempt", { actor: "executor", expectedVersion: 0, expectedActionVersion: 2, outcome: "unknown_outcome" });
    assert.throws(() => action.ready("a", options(3)), { code: "invalid_transition" });
    action.beginReconciliation("a", options(3));
    action.reconcile("a", { actor: "operator", expectedVersion: 4, expectedAttemptVersion: 1, outcome: "failed", reconciliationRef: "query-no-effect" });
    action.ready("a", options(5));
    mission.requestCancel("m", options(1));
    assert.equal(action.get("a").state, "cancel_requested");
    assert.throws(() => action.assertExecutionAllowed("a", 0), { code: "stale_epoch" });
    action.drain("a", options(action.get("a").version));
    action.finishCancellation("a", options(action.get("a").version));
    assert.equal(store.get("action", "a").state, "cancelled");
});
